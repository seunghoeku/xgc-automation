"""Install a per-user launchd timer and a cache-only SwiftBar plugin."""

from __future__ import annotations

import os
import plistlib
import shlex
import subprocess
import sys
from pathlib import Path

from .config import Config, app_dir

LABEL = "org.hpc-queue-monitor.poll"
PLUGIN = "hpc-monitor.30s.sh"
MARKER = "# Generated by hpc-queue-monitor"


def service_file() -> Path:
    return Path.home() / "Library" / "LaunchAgents" / f"{LABEL}.plist"


def log_file() -> Path:
    return Path.home() / "Library" / "Logs" / "hpc-queue-monitor.log"


def _launchctl(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(["/bin/launchctl", *args], capture_output=True, text=True,
                          check=check, timeout=30)


def service_loaded() -> bool:
    return _launchctl("print", f"gui/{os.getuid()}/{LABEL}", check=False).returncode == 0


def stop() -> None:
    if service_loaded():
        _launchctl("bootout", f"gui/{os.getuid()}/{LABEL}")


def start() -> None:
    if not service_file().is_file():
        raise ValueError("Timer is not installed. Run 'hpc-monitor install' first.")
    if not service_loaded():
        _launchctl("bootstrap", f"gui/{os.getuid()}", str(service_file()))


def plugin_dir() -> Path:
    result = subprocess.run(
        ["/usr/bin/defaults", "read", "com.ameba.SwiftBar", "PluginDirectory"],
        capture_output=True, text=True, timeout=5,
    )
    value = result.stdout.strip()
    if result.returncode == 0 and value:
        return Path(value).expanduser().resolve()
    return app_dir() / "plugins"


def plugin_text(config: Config, python: str) -> str:
    command = shlex.join([python, "-m", "hpc_monitor", "--config", str(config.path), "menu"])
    return f'''#!/bin/bash
{MARKER}
# <swiftbar.title>HPC Queue Monitor</swiftbar.title>
# <swiftbar.desc>Slurm/PBS jobs and recent departures from the local cache.</swiftbar.desc>
# <swiftbar.version>0.1.0</swiftbar.version>
# <swiftbar.runInBash>false</swiftbar.runInBash>
if [ ! -x {shlex.quote(python)} ]; then
    printf '%s\\n' 'HPC ⚠' '---' 'Monitor runtime missing. Reinstall hpc-queue-monitor and run hpc-monitor install.'
    exit 0
fi
{command}
'''


def timer_data(config: Config, python: str) -> dict:
    return {
        "Label": LABEL,
        "ProgramArguments": [python, "-m", "hpc_monitor", "--config", str(config.path),
                             "poll", "--rotate-log", str(log_file())],
        "WorkingDirectory": str(app_dir()),
        "StartInterval": config.poll_interval,
        "RunAtLoad": True,
        "ProcessType": "Background",
        "EnvironmentVariables": {"PATH": "/usr/bin:/bin:/usr/sbin:/sbin"},
        "StandardOutPath": str(log_file()),
        "StandardErrorPath": str(log_file()),
        "HPCMonitorConfig": str(config.path),
    }


def _owned_timer() -> dict | None:
    path = service_file()
    if not path.exists():
        return None
    data = plistlib.loads(path.read_bytes())
    if data.get("Label") != LABEL or not data.get("HPCMonitorConfig"):
        raise ValueError(f"Refusing to change an unmanaged timer: {path}")
    return data


def _owned_plugin(path: Path) -> None:
    if path.exists() and MARKER not in path.read_text(encoding="utf-8").splitlines():
        raise ValueError(f"Refusing to change an unmanaged plugin: {path}")


def install(config: Config, directory: Path | None, *, dry_run: bool, no_start: bool) -> None:
    directory = (directory or plugin_dir()).expanduser().resolve()
    plugin = directory / PLUGIN
    _owned_plugin(plugin)
    old = _owned_timer()
    if old and old.get("HPCMonitorConfig") != str(config.path):
        raise ValueError("A different config is installed. Uninstall it before switching configs.")
    old_plugin = Path(old["HPCMonitorPlugin"]) if old and "HPCMonitorPlugin" in old else None
    if old_plugin and old_plugin != plugin:
        raise ValueError("Plugin folder changed. Uninstall the previous installation first.")
    # Keep the venv executable path: resolving its symlink would lose the package.
    python = os.path.abspath(sys.executable)
    timer = timer_data(config, python)
    timer["HPCMonitorPlugin"] = str(plugin)
    print(f"Config: {config.path}\nPlugin: {plugin}\nTimer: {service_file()}")
    print(f"Poll every {config.poll_interval}s; menu refresh every 30s")
    if dry_run:
        print("Dry run: no files or services changed.")
        return
    stop()
    app_dir().mkdir(parents=True, exist_ok=True)
    directory.mkdir(parents=True, exist_ok=True)
    service_file().parent.mkdir(parents=True, exist_ok=True)
    log_file().parent.mkdir(parents=True, exist_ok=True)
    plugin.write_text(plugin_text(config, python), encoding="utf-8")
    plugin.chmod(0o700)
    service_file().write_bytes(plistlib.dumps(timer))
    service_file().chmod(0o600)
    if not no_start:
        start()
        print("Queue polling started and will resume at login.")
    print(f"In SwiftBar, choose this Plugin Folder if not already selected: {directory}")
    print("Enable SwiftBar's Launch at Login option for the menu to resume at login.")


def uninstall(*, yes: bool) -> None:
    data = _owned_timer()
    if not data:
        print("No managed installation found.")
        return
    plugin = Path(data["HPCMonitorPlugin"])
    if plugin.name != PLUGIN:
        raise ValueError("Unrecognized plugin filename in the installation record")
    _owned_plugin(plugin)
    print(f"Remove timer: {service_file()}\nRemove plugin: {plugin}")
    if not yes:
        print("Rerun with --yes to remove these files. Config, cache and logs will be kept.")
        return
    stop()
    plugin.unlink(missing_ok=True)
    service_file().unlink()
    print("Removed the monitor timer and plugin. Config, cache and logs were kept.")
